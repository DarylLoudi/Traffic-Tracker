let lang = 'en';
try {
  const saved = localStorage.getItem('arus-lang');
  lang = saved === 'id' || saved === 'en' ? saved : (navigator.language || '').toLowerCase().startsWith('id') ? 'id' : 'en';
} catch {
  /* storage blocked */
}

export const getLang = () => lang;
export function setLang(l) {
  lang = l;
  try {
    localStorage.setItem('arus-lang', l);
  } catch {}
}
export const t = (key, ...args) => {
  const v = dict[lang][key] ?? dict.en[key];
  return typeof v === 'function' ? v(...args) : v;
};

/** Fill static [data-i18n] text and placeholders. */
export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
}
